// Generates ui/browser-chrome/src/generated/icon-glyphs.ts: the exact SVG glyph
// strings of every @atlaskit/icon/core/* module imported by the sidebar source.
// The Trusted Types default policy (src/trusted-types.ts) accepts innerHTML
// only when the value is byte-identical to one of these strings.
//   bun scripts/ui/gen-icon-glyphs.ts [--check]
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const ui = join(import.meta.dir, '../../ui/browser-chrome');
const src = join(ui, 'src');
const out = join(src, 'generated/icon-glyphs.ts');
const walk = (d: string): string[] => readdirSync(d).flatMap(f => { const p = join(d, f); return statSync(p).isDirectory() ? (f === 'generated' || f === '__tests__' ? [] : walk(p)) : /\.(tsx?|jsx?)$/.test(f) ? [p] : []; });
const icons = new Set<string>();
for (const f of walk(src)) for (const m of readFileSync(f, 'utf8').matchAll(/from ['"]@atlaskit\/icon\/core\/([a-z0-9-]+)['"]/g)) icons.add(m[1]);
const iconRoot = join(import.meta.dir, '../../node_modules/@atlaskit/icon');
const iconVersion = JSON.parse(readFileSync(join(iconRoot, 'package.json'), 'utf8')).version;
const entries: Array<[string, string]> = [];
for (const name of [...icons].sort()) {
  const code = readFileSync(join(iconRoot, 'core', `${name}.js`), 'utf8');
  const m = code.match(/dangerouslySetGlyph:\s*(?:`([^`]*)`|"((?:[^"\\]|\\.)*)")/);
  if (!m) throw new Error(`no glyph found for @atlaskit/icon/core/${name}`);
  const glyph = m[1] ?? JSON.parse(`"${m[2]}"`);
  if (/<\s*(script|foreignObject|iframe|use)\b|\son[a-z]+=|javascript:/i.test(glyph)) throw new Error(`unsafe markup in glyph ${name}`);
  entries.push([name, glyph]);
}
const content = `// GENERATED by scripts/ui/gen-icon-glyphs.ts from @atlaskit/icon@${iconVersion}. Do not edit.\n` +
  `// Exact SVG glyph markup accepted by the Trusted Types default policy.\n` +
  `export const ICON_GLYPHS: ReadonlyMap<string, string> = new Map([\n${entries.map(([n, g]) => `  [${JSON.stringify(n)}, ${JSON.stringify(g)}],`).join('\n')}\n]);\n`;
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== content) { console.error('drift: src/generated/icon-glyphs.ts (run bun scripts/ui/gen-icon-glyphs.ts)'); process.exit(1); }
  console.error(`icon glyph allowlist up to date (${entries.length} icons)`);
} else {
  mkdirSync(join(src, 'generated'), { recursive: true });
  writeFileSync(out, content);
  console.error(`wrote ${entries.length} icon glyphs`);
}
