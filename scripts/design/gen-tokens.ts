// Generates ui/browser-chrome/src/design-system/tokens.generated.css from
// design/tokens.json + design/figma/snapshot.json. `--check` fails on drift.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dir, '../..');
const tokens = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'));
const snap = JSON.parse(readFileSync(join(root, 'design/figma/snapshot.json'), 'utf8'));
const outPath = join(root, 'ui/browser-chrome/src/design-system/tokens.generated.css');
const themes: string[] = tokens.themes;
const problems: string[] = [];

type Tok = { figmaVar?: string; fallbackTheme?: string; literal?: Record<string, string>; derived?: Record<string, string>; usage?: string };

function colorFor(name: string, t: Tok, theme: string): { value: string; source: string } {
  if (t.figmaVar) {
    const v = snap.variables[t.figmaVar];
    if (!v) problems.push(`${name}: ${t.figmaVar} not in snapshot`);
    const val = v?.values?.[theme];
    if (val) return { value: val, source: `figma ${t.figmaVar.replace('VariableID:', '')}` };
    if (t.fallbackTheme && v?.values?.[t.fallbackTheme]) return { value: v.values[t.fallbackTheme], source: `figma ${t.figmaVar.replace('VariableID:', '')} (${t.fallbackTheme} value; unbound in ${theme})` };
    problems.push(`${name}: no value for theme ${theme}`);
    return { value: 'magenta', source: 'MISSING' };
  }
  if (t.literal?.[theme]) return { value: t.literal[theme], source: 'figma literal' };
  if (t.derived?.[theme]) return { value: t.derived[theme], source: 'derived (not in Figma)' };
  problems.push(`${name}: no value for theme ${theme}`);
  return { value: 'magenta', source: 'MISSING' };
}

const px = (n: number) => `${n}px`;
let css = `/* GENERATED by scripts/design/gen-tokens.ts from design/tokens.json and\n * design/figma/snapshot.json (Figma file ${snap.source.fileKey}, version ${snap.source.version}).\n * Do not edit by hand: run \`bun run design:tokens\`. */\n\n`;
css += ':root {\n  --js-font: -apple-system, BlinkMacSystemFont, "SF Pro", system-ui, sans-serif;\n';
for (const [k, v] of Object.entries(tokens.size as Record<string, number>)) css += `  --js-size-${k}: ${px(v)};\n`;
for (const [k, v] of Object.entries(tokens.radius as Record<string, number>)) css += `  --js-radius-${k}: ${px(v)};\n`;
for (const [k, v] of Object.entries(tokens.opacity as Record<string, number>)) css += `  --js-opacity-${k}: ${v};\n`;
for (const [k, v] of Object.entries(tokens.type as Record<string, any>)) {
  if (k.startsWith('$')) continue;
  css += `  --js-type-${k}: ${v.weight} ${px(v.size)}/${px(v.lineHeight)} var(--js-font);\n`;
  if (v.letterSpacing) css += `  --js-type-${k}-tracking: ${px(v.letterSpacing)};\n`;
}
css += '}\n';
// Light is the :root fallback and must come FIRST: [data-theme] selectors have the
// same specificity as :root, so later rules win.
for (const theme of ['light', ...themes.filter(t => t !== 'light')]) {
  const sel = theme === 'light' ? ':root, [data-theme="light"]' : `[data-theme="${theme}"]`;
  css += `\n${sel} {\n  color-scheme: ${theme === 'dark' ? 'dark' : 'light'};\n`;
  for (const [name, t] of Object.entries(tokens.colors as Record<string, Tok>)) {
    const { value, source } = colorFor(name, t, theme);
    css += `  --js-color-${name}: ${value}; /* ${source} */\n`;
  }
  css += '}\n';
}

if (problems.length) { console.error('token generation problems:\n  ' + problems.join('\n  ')); process.exit(1); }
if (process.argv.includes('--check')) {
  const cur = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (cur !== css) { console.error(`${outPath} is stale: run bun run design:tokens`); process.exit(1); }
  console.error('tokens up to date');
} else {
  writeFileSync(outPath, css);
  console.error(`wrote ${outPath}`);
}
